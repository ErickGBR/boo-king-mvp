import { Injectable } from '@nestjs/common';
import nodemailer from 'nodemailer';

/**
 * MailerService — MOVED VERBATIM from `src/services/email.js`.
 * Same transporter options, same `es-SV` formatting, same templates, same
 * fire-and-forget semantics: `sendConfirmationEmail` / `sendRescheduleEmail`
 * swallow + log any transport error so a failing SMTP server never blocks the
 * booking flow. `sendPasswordResetEmail` follows the same contract so the
 * forgot-password endpoint can always answer with a generic `{ ok: true }`.
 */
@Injectable()
export class MailerService {
  private getTransporter() {
    return nodemailer.createTransport({
      host: process.env.SMTP_HOST || 'smtp.ethereal.email',
      port: Number(process.env.SMTP_PORT) || 587,
      secure: process.env.SMTP_SECURE === 'true',
      auth: {
        user: process.env.SMTP_USER || '',
        pass: process.env.SMTP_PASS || '',
      },
    });
  }

  private get from(): string {
    return process.env.SMTP_FROM || 'noreply@boo-king.com';
  }

  private get frontendUrl(): string {
    return process.env.FRONTEND_URL || 'http://localhost:3000';
  }

  async sendConfirmationEmail(appointment: any, business: any): Promise<void> {
    const { guestName, guestEmail, startsAt, guestPhone } = appointment;
    try {
      const transporter = this.getTransporter();
      const date = new Date(startsAt).toLocaleString('es-SV', {
        dateStyle: 'full',
        timeStyle: 'short',
        timeZone: business.timezone,
      });
      const bookingUrl = `${this.frontendUrl}/b/${business.slug}`;
      await transporter.sendMail({
        from: this.from,
        to: guestEmail,
        subject: `Cita confirmada en ${business.name}`,
        html: `<div style="font-family:sans-serif;max-width:480px;margin:0 auto">
        <h2 style="color:#14b8a6">¡Cita confirmada!</h2>
        <p>Hola <strong>${guestName}</strong>,</p>
        <p>Tu cita en <strong>${business.name}</strong> ha sido confirmada.</p>
        <table style="width:100%;border-collapse:collapse;margin:16px 0">
          <tr><td style="padding:8px;border:1px solid #ddd;font-weight:600">Fecha</td>
              <td style="padding:8px;border:1px solid #ddd">${date}</td></tr>
          ${guestPhone ? `<tr><td style="padding:8px;border:1px solid #ddd;font-weight:600">Teléfono</td>
              <td style="padding:8px;border:1px solid #ddd">${guestPhone}</td></tr>` : ''}
          ${business.address ? `<tr><td style="padding:8px;border:1px solid #ddd;font-weight:600">Dirección</td>
              <td style="padding:8px;border:1px solid #ddd">${business.address}</td></tr>` : ''}
        </table>
        <p style="color:#666">Si necesitas reprogramar, visita el enlace:
          <br><a href="${bookingUrl}" style="color:#14b8a6">${bookingUrl}</a></p>
      </div>`,
      });
    } catch (err) {
      console.error('Email send error:', err);
    }
  }

  /**
   * Sends a freshly generated password to the account owner.
   *
   * `newPassword` is the clear-text value generated by the forgot-password
   * flow; it must reach the user ONLY through this e-mail (it is bcrypt-hashed
   * before being persisted). Same fire-and-forget contract as the booking
   * senders: a dead SMTP server is logged, never thrown, so the endpoint can
   * keep answering with its generic `{ ok: true }`.
   */
  async sendPasswordResetEmail(email: string, newPassword: string): Promise<void> {
    try {
      const transporter = this.getTransporter();
      await transporter.sendMail({
        from: this.from,
        to: email,
        subject: 'Tu nueva contraseña de Boo-king',
        text: `Hola,\n\nHemos recibido una solicitud para restablecer tu contraseña.\n\nTu nueva contraseña es: ${newPassword}\n\nInicia sesión con ella y cámbiala desde tu perfil. Si no solicitaste este cambio, contacta con soporte.\n`,
        html: `<div style="font-family:sans-serif;max-width:480px;margin:0 auto">
        <h2 style="color:#14b8a6">Nueva contraseña</h2>
        <p>Hola,</p>
        <p>Hemos recibido una solicitud para restablecer tu contraseña.</p>
        <table style="width:100%;border-collapse:collapse;margin:16px 0">
          <tr><td style="padding:8px;border:1px solid #ddd;font-weight:600">Contraseña</td>
              <td style="padding:8px;border:1px solid #ddd;font-family:monospace">${newPassword}</td></tr>
        </table>
        <p>Inicia sesión con ella y cámbiala desde tu perfil.</p>
        <p style="color:#666">Si no solicitaste este cambio, contacta con soporte.</p>
      </div>`,
      });
    } catch (err) {
      console.error('Password reset email error:', err);
    }
  }

  async sendRescheduleEmail(appointment: any, business: any): Promise<void> {
    const { guestName, guestEmail, startsAt } = appointment;
    try {
      const transporter = this.getTransporter();
      const date = new Date(startsAt).toLocaleString('es-SV', {
        dateStyle: 'full',
        timeStyle: 'short',
        timeZone: business.timezone,
      });
      await transporter.sendMail({
        from: this.from,
        to: guestEmail,
        subject: `Cita reprogramada en ${business.name}`,
        html: `<div style="font-family:sans-serif;max-width:480px;margin:0 auto">
        <h2 style="color:#14b8a6">Cita reprogramada</h2>
        <p>Hola <strong>${guestName}</strong>,</p>
        <p>Tu cita en <strong>${business.name}</strong> ha sido reprogramada.</p>
        <p><strong>Nueva fecha:</strong> ${date}</p>
        <p style="color:#666">Si tienes dudas, contacta al negocio directamente.</p>
      </div>`,
      });
    } catch (err) {
      console.error('Reschedule email error:', err);
    }
  }
}
